  Mate.prototype.label = function (x, y) {
    const L = this.lab, s = this.labScale;
    const ix = Math.max(0, Math.min(L.width - 1, Math.round(x * s))), iy = Math.max(0, Math.min(L.height - 1, Math.round(y * s)));
    const i = (iy * L.width + ix) * 4, D = L.data;
    return [D[i] / 255, D[i + 1] / 255, D[i + 2] / 255];
  };

  Mate.prototype.weigh = function (x, y) {
    const r = this.rig, [hairL, cloth, body] = this.label(x, y);
    const [ar0, ar1] = r.armRadius || [16, 34];
    /* 腕：どちらの腕か（side）・肩からどこまで来たか（at 0→1）。肩を支点に回すのに使う */
    let arm = 0, side = 0, at = 0;
    [r.armL, r.armR].forEach((poly, i) => {
      if (!poly) return;
      const [d, t] = polyNear(x, y, poly);
      let w = d < ar1 ? 1 - smooth(ar0, ar1, d) : 0;
      const hb = Math.min(1, blob(x, y, poly[poly.length - 1], r.handRadius || 0) * 1.3);
      let tt = t;
      if (hb > w) { w = hb; tt = 1; }
      if (w > arm) { arm = w; side = i; at = tt; }
    });
    arm = Math.min(1, arm) * (1 - Math.min(1, hairL * 1.2) * 0.7);
    const swing = r.armSwing ? r.armSwing[side] : 1;
    const above = smooth(r.neck[1] + 40, r.neck[1] - 30, y);          /* 首は広めになだらかに（折れて見えないように） */
    const hairRoot = hairL * Math.exp(-Math.max(0, y - r.neck[1]) / 150);
    const w = { arm, side, at, swing };
    /* 腕（頭に添えた手も）は頭の回転に乗せない：乗せると手首・前腕が引きのばされてゆがむ */
    w.head = Math.min(1, Math.max(above, hairRoot * 0.9)) * (1 - arm);
    w.face = r.faceRadius > 0 ? Math.pow(Math.max(0, 1 - Math.hypot(x - r.face[0], y - r.face[1]) / r.faceRadius), 1.5) * (1 - hairL * 0.8) : 0;
    w.torso = smooth(r.waistY, r.shoulderY, y);
    w.shoulder = smooth(r.shoulderY + 90, r.shoulderY - 10, y) * (1 - above);
    w.bust = r.bustAmount * (blob(x, y, r.bustL, r.bustRadius) + blob(x, y, r.bustR, r.bustRadius)) * Math.min(1, body) * (1 - hairL * 0.8) * (1 - arm * 0.8);
    const fall = smooth(r.hairStart != null ? r.hairStart : r.neck[1] - 40, r.neck[1] + r.hairFall, y);   /* 短い髪は hairStart で早めに揺らす */
    w.hair = Math.min(1, hairL * 1.2) * fall * (1 + Math.min(1, Math.max(0, (y - r.neck[1] - r.hairFall) / 260)) * 0.5);
    /* 袖（腕の上の布）は揺らさない：腕と布が別々に動くと腕がゆがんで見える */
    w.cloth = Math.min(1, cloth * 1.3) * smooth(r.shoulderY + 40, r.hemY, y) * (1 - smooth(r.hemY + 40, r.hemY + 160, y) * 0.7) * (1 - hairL) * (1 - Math.min(1, arm * 1.5));
    w.iris = Math.max(blob(x, y, r.irisL, r.irisRadius * 1.5), blob(x, y, r.irisR, r.irisRadius * 1.5));
    w.hip = smooth(r.pivot[1], r.waistY, y);
    w.legs = smooth(r.hemY, r.kneeY, y);
    return w;
  };

  Mate.prototype.buildMesh = function () {
    const W = this.W, H = this.H, S = 8, A = this.alpha;
    const cols = Math.ceil(W / S), rows = Math.ceil(H / S);
    const idx = new Int32Array((cols + 1) * (rows + 1)).fill(-1);
    const rest = [], tris = [];
    const V = (i, j) => { const k = j * (cols + 1) + i; if (idx[k] < 0) { idx[k] = rest.length / 2; rest.push(Math.min(i * S, W), Math.min(j * S, H)); } return idx[k]; };
    for (let cy = 0; cy < rows; cy++) for (let cx = 0; cx < cols; cx++) {
      let any = false;
      for (let y = cy * S - 1; y <= cy * S + S && !any; y += 2) for (let x = cx * S - 1; x <= cx * S + S; x += 2) {
        if (x < 0 || y < 0 || x >= W || y >= H) continue; if (A[(y * W + x) * 4 + 3] > 4) { any = true; break; }
      }
      if (!any) continue;
      const a = V(cx, cy), b = V(cx + 1, cy), c = V(cx + 1, cy + 1), d = V(cx, cy + 1);
      tris.push(a, b, c, a, c, d);
    }
    const n = rest.length / 2;
    this.rest = new Float32Array(rest); this.pos = new Float32Array(rest.length);
    this.uv = new Float32Array(rest.length); this.tris = n > 65535 ? new Uint32Array(tris) : new Uint16Array(tris);
    this.w = new Array(n);
    for (let i = 0; i < n; i++) {
      const x = rest[i * 2], y = rest[i * 2 + 1];
      this.uv[i * 2] = x / W; this.uv[i * 2 + 1] = y / H;
      this.w[i] = this.weigh(x, y);
    }
    /* ★★ 2026-09-24d 重みを格子の上でならす。
       範囲の目印は1〜2マスで切りかわるので、そのままだと「髪だけ・腕だけ」が動いて境目の三角形が
       引きのばされ、首・目元・腕・水着のふちがゆがんで見えた。まわりとの平均を何回か取って、
       切りかわりを数マスに広げる（動く量そのものはほとんど変わらない）。 */
    const nb = new Array(n);
    for (let j = 0; j <= rows; j++) for (let i = 0; i <= cols; i++) {
      const k = idx[j * (cols + 1) + i]; if (k < 0) continue;
      const list = [];
      for (const [di, dj] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
        const ii = i + di, jj = j + dj;
        if (ii < 0 || jj < 0 || ii > cols || jj > rows) continue;
        const kk = idx[jj * (cols + 1) + ii]; if (kk >= 0) list.push(kk);
      }
      nb[k] = list;
    }
    const KEYS = ["head", "face", "torso", "shoulder", "arm", "bust", "hair", "cloth", "iris", "hip", "legs"];
    const PASSES = { hair: 6, cloth: 8, arm: 4, head: 5, face: 4, bust: 8, iris: 1 };
    for (const key of KEYS) {
      const passes = PASSES[key] || 2;
      let cur = new Float32Array(n), nxt = new Float32Array(n);
      for (let i = 0; i < n; i++) cur[i] = this.w[i][key] || 0;
      for (let p = 0; p < passes; p++) {
        for (let i = 0; i < n; i++) {
          const L = nb[i]; if (!L || !L.length) { nxt[i] = cur[i]; continue; }
          let sum = 0; for (let q = 0; q < L.length; q++) sum += cur[L[q]];
          nxt[i] = cur[i] * 0.5 + (sum / L.length) * 0.5;
        }
        const t = cur; cur = nxt; nxt = t;
      }
      for (let i = 0; i < n; i++) this.w[i][key] = cur[i];
    }
    this.vcount = n;
    this.motion = { hair: 0, cloth: 0, bust: 0, head: 0, arm: 0, legs: 0 };
  };

  /* 1点の変形（ピクセル座標・上が0） */
  Mate.prototype.deform = function (x, y, w, o) {
    const r = this.rig;
    let qx = x, qy = y;
    qy -= o.breath * w.torso;
    qx += this.body.x * w.torso; qy += this.body.y * w.torso;
    qy += this.hop.y * w.hip;
    /* 腕：肩を支点に回す。手先ほど大きく動く（at）。腕の形は変えずに向きだけ変わる */
    if (w.arm > 0.001 && w.swing > 0) {
      const ang = (o.armAng + this.swing.x) * w.swing * Math.pow(w.at, 1.15) * w.arm * Math.PI / 180;
      if (ang) {
        const sp = (w.side ? r.armR : r.armL)[0], dx = qx - sp[0], dy = qy - sp[1], cs = Math.cos(ang), sn = Math.sin(ang);
        qx = sp[0] + dx * cs - dy * sn; qy = sp[1] + dx * sn + dy * cs;
      }
    }
    if (w.head > 0) {
      const ang = (o.tilt + this.jolt.x) * w.head * Math.PI / 180;
      const nx = r.neck[0] + this.body.x, ny = r.neck[1] + this.body.y + this.hop.y - o.breath;
      const dx = qx - nx, dy = qy - ny, cs = Math.cos(ang), sn = Math.sin(ang);
      qx = nx + dx * cs - dy * sn; qy = ny + dx * sn + dy * cs;
      qx += o.headX * w.head; qy += o.headY * w.head;
    }
    /* ★ 2026-09-24g 瞳は動かさない（1枚絵の瞳だけを動かすと、まつ毛や白目が引きのばされて見えた）。
       視線は頭の傾きと向きだけで表す */
    qx += o.turn * 1.5 * w.head;
    qx += this.hair.x * w.hair; qy += (Math.abs(this.hair.x) * 0.18 + this.hair.y * 0.4) * w.hair;
    qx += this.cloth.x * w.cloth; qy += this.cloth.y * 0.5 * w.cloth;
    qx += this.bust.x * 0.35 * w.bust; qy += this.bust.y * w.bust;
    qx += o.hipX * w.hip;
    if (o.lean) {
      const la = o.lean * Math.PI / 180, dx = qx - r.pivot[0], dy = qy - r.pivot[1], cs = Math.cos(la), sn = Math.sin(la);
      qx = r.pivot[0] + dx * cs - dy * sn; qy = r.pivot[1] + dx * sn + dy * cs;
    }
    return [qx, qy];
  };

  Mate.prototype.update = function (dt, now) {
    const t = (this.t += dt), r = this.rig, amp = RM ? 0.45 : 1, P = this.pose;
    if (this.exprUntil && now > this.exprUntil) { this.exprUntil = 0; this.expr = "neutral"; }
    const E = EXPR[this.expr] || EXPR.neutral;
    const k = 1 - Math.exp(-dt * 6);
    P.tilt += (E[1] - P.tilt) * k; P.head[1] += (E[2] - P.head[1]) * k; P.lean += (E[3] - P.lean) * k;
    const gt = [Math.max(-1, Math.min(1, this.look[0])), Math.max(-1, Math.min(1, this.look[1] + E[4]))];
    const kg = 1 - Math.exp(-dt * 9);
    P.gaze[0] += (gt[0] - P.gaze[0]) * kg; P.gaze[1] += (gt[1] - P.gaze[1]) * kg;

    const breath = (1 - Math.cos(t * 2 * Math.PI / 4.2)) * 0.5;
    const o = {
      breath: breath * 3.4 * amp,
      tilt: (0.7 * Math.sin(t * 0.55 + this.seed) + 0.25 * Math.sin(t * 1.27)) * amp + P.tilt - P.gaze[0] * 1.2,
      headX: P.gaze[0] * 1.2, headY: P.head[1] + P.gaze[1] * 1.0,
      turn: P.gaze[0] * 0.9, gx: P.gaze[0], gy: P.gaze[1],
      armAng: 0.5 * Math.sin(t * 0.8 + 1) * amp,                 /* 振る腕だけ、ゆっくり振れる（度） */
      hipX: (4.5 * Math.sin(t * 0.33 + this.seed) + 1.5 * Math.sin(t * 0.91)) * amp,
      lean: (0.25 * Math.sin(t * 0.41 + this.seed)) * amp + P.lean
    };
    this.o = o;
    stepSpring(this.body, 0, 0, 80, 11, dt, 18);
    stepSpring(this.jolt, 0, 0, 60, 8, dt, 5);        /* 首の傾き（度）。大きいと首が折れて見える */
    stepSpring(this.hop, 0, 0, 55, 7, dt, 16);
    stepSpring(this.swing, 0, 0, 38, 5.5, dt, 4);      /* 腕の振り（度）。手先は肩から遠いので数度でも大きく動く */
    if (!this.refW) this.refW = this.weigh(r.neck[0], r.neck[1]);
    const ref = this.deform(r.neck[0], r.neck[1], this.refW, o);
    if (!this.prev) { this.prev = ref; this.prev2 = ref; }
    let ax = (ref[0] - 2 * this.prev[0] + this.prev2[0]) / (dt * dt), ay = (ref[1] - 2 * this.prev[1] + this.prev2[1]) / (dt * dt);
    const am = Math.hypot(ax, ay); if (am > 6000) { ax *= 6000 / am; ay *= 6000 / am; }
    this.prev2 = this.prev; this.prev = ref;
    const wind = (Math.sin(t * 0.8 + this.seed) * 5 + Math.sin(t * 1.9) * 2.5) * amp;
    stepSpring(this.hair, -ax * 0.6 + wind * 9, -ay * 0.4, 14, 3.2, dt, 15);
    stepSpring(this.cloth, -ax * 0.5 + wind * 6, -ay * 0.3, 32, 5.5, dt, 8);
    const boost = now < (this.bustBoostUntil || 0);                   /* 胸をさわった直後は大きく・長めに揺れる */
    stepSpring(this.bust, -ax * 0.3, -ay * 0.8 + (breath - 0.5) * 45, boost ? 70 : 62, boost ? 2.6 : 4.6, dt, boost ? 18 : 8);

    const face = E[0];
    let blink = false;
    if (this.blinkT < 0 && now >= this.blinkAt && !NO_BLINK[face]) this.blinkT = 0;
    if (this.blinkT >= 0) {
      this.blinkT += dt;
      /* まばたきは「開→閉→開」だけ（閉じた目の絵の目だけを一瞬重ねる） */
      if (this.blinkT < 0.12) blink = true;
      else { this.blinkT = -1; this.blinkAt = now + (Math.random() < 0.2 ? 250 : 2200 + Math.random() * 3500); }
    }
    if (face !== this.shown.face || blink !== this.shown.blink) this.compose(face, blink);

    const R = this.rest, Q = this.pos, M = this.motion;
    M.hair = M.cloth = M.bust = M.head = M.arm = M.legs = 0;
    for (let i = 0; i < this.vcount; i++) {
      const x = R[i * 2], y = R[i * 2 + 1], w = this.w[i];
      const q = this.deform(x, y, w, o);
      Q[i * 2] = q[0]; Q[i * 2 + 1] = q[1];
      const d = Math.hypot(q[0] - x, q[1] - y);
      if (w.hair > 0.5 && d > M.hair) M.hair = d;
      if (w.cloth > 0.5 && d > M.cloth) M.cloth = d;
      if (w.bust > 0.3 && d > M.bust) M.bust = d;
      if (w.head > 0.9 && d > M.head) M.head = d;
      if (w.arm > 0.6 && d > M.arm) M.arm = d;
      if (w.legs > 0.6 && w.hip < 0.9 && d > M.legs) M.legs = d;
    }
  };

  Mate.prototype.compose = function (face, blink) {
    const [fx, fy, fw, fh] = this.faceRect, c = this.faceCtx, F = this.rig.face_patches;
    c.clearRect(0, 0, fw, fh);
    c.drawImage(this.baseCv, fx, fy, fw, fh, 0, 0, fw, fh);
    const put = (name) => {
      const p = F[name]; if (!p) return;
      c.drawImage(this.faceImg, p.rect[0], p.rect[1], p.rect[2], p.rect[3], p.at[0] - fx, p.at[1] - fy, p.rect[2], p.rect[3]);
    };
    if (face) put("x_" + face);
    else if (F.x_neutral) put("x_neutral");        /* ★ 立ち絵がウインクの子（莉沙）は、ふだんの顔も目を開けた絵を重ねる */
    if (blink) put("blink");
    this.shown = { face, blink };
    this.dirtyFace = true;
    this.composeCount = (this.composeCount || 0) + 1;
  };

