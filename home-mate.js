  Mate.prototype.regionAt = function (px, py) {
    const r = this.rig, ix = Math.round(px), iy = Math.round(py);
    if (ix < 0 || iy < 0 || ix >= this.W || iy >= this.H) return null;
    if (this.alpha[(iy * this.W + ix) * 4 + 3] < 60) return null;
    const w = this.weigh(px, py);
    /* ★★ 2026-09-25h 胸の楕円（左右それぞれ・下側は広め＝下乳まで）の中は<b>胸が先</b>。
       前は腕の範囲（太め）が先に効いて、こちらから見て左の胸の外側が「腕」、下乳が「お腹」になっていた。
       胸の中で「腕」になるのは、腕の芯（中心線のすぐ近く）に触ったときだけ */
    if (r.bustRadius > 0 && py > r.shoulderY + 6 && py > r.neck[1] + 6) {
      const R = r.bustRadius, below = r.bustBelow || 1.25;
      let inChest = false;
      for (const c of [r.bustL, r.bustR]) {
        const dx = (px - c[0]) / (R * 0.98), dy = (py - c[1]) / (R * (py < c[1] ? 0.8 : below));
        if (dx * dx + dy * dy < 1) { inChest = true; break; }
      }
      /* 左右の胸のあいだ（谷間）も胸 */
      const lo = Math.min(r.bustL[0], r.bustR[0]), hi = Math.max(r.bustL[0], r.bustR[0]), cy = (r.bustL[1] + r.bustR[1]) / 2;
      if (!inChest && px > lo && px < hi && py > cy - R * 0.8 && py < cy + R * below * 0.95) inChest = true;
      if (inChest) {
        const [ar0] = r.armRadius || [16, 34];
        let onArm = false;
        [r.armL, r.armR].forEach((poly) => { if (poly && polyNear(px, py, poly)[0] < ar0 * 0.75) onArm = true; });
        return onArm ? "arm" : "chest";
      }
    }
    if (w.arm > 0.6 && w.swing > 0 && py > r.shoulderY) return "arm";
    if (py < r.neck[1] + 6) return "head";
    if (w.bust > 0.3) return "chest";
    /* ★ 2026-09-24e 胸の下側（下乳）は重みが薄くて「お腹」になっていた→胸の中心から半径ぶん下までは胸 */
    if (r.bustRadius > 0 && w.arm < 0.5) {
      const bx = (r.bustL[0] + r.bustR[0]) / 2, by = (r.bustL[1] + r.bustR[1]) / 2;
      const halfW = Math.abs(r.bustR[0] - r.bustL[0]) / 2 + r.bustRadius * 0.85;
      if (py > r.shoulderY + 20 && py < by + r.bustRadius * 0.95 && Math.abs(px - bx) < halfW) return "chest";
    }
    /* ★★ 2026-09-25 パンツ（水着の下・裾の中）は<b>キャラごとの枠</b>（rig.pants）。股の下のほうと、
       その上に重ねた手も含める（前は下のほうが「脚」、手が「腕」になっていた） */
    if (r.pants) {
      const [x0, y0, x1, y1] = r.pants;
      if (px > x0 && px < x1 && py > y0 && py < y1 && !(w.arm > 0.6 && w.swing > 0)) return "pants";
    }
    if (w.arm > 0.55) return "arm";
    if (!r.pants) {
      const bx = (r.bustL[0] + r.bustR[0]) / 2, bw = Math.abs(r.bustR[0] - r.bustL[0]) * 0.62 + 24;
      if (py > r.waistY + (r.hemY - r.waistY) * 0.45 && py < r.hemY + 60 && Math.abs(px - bx) < bw) return "pants";
    }
    if (py > r.hemY + 30) return "legs";
    return "waist";
  };

