  /* ── キャラクターの名前を自動で作る ──
     台帳の画像ファイル名がローマ字なので、そこから英語表記を引く。
     例: 「カホ」/ ../img/Kaho.webp → "Kaho"、「アンナ(祭)」→ "Anna (Fest)"
     ★ 手で並べると<b>キャラが増えるたびに抜ける</b>ので、必ず台帳から作ること。 */
  function buildCharNames() {
    if (!window.XEVA || !window.XEVA.iconCharList) return false;
    var map = {}, list;
    try { list = window.XEVA.iconCharList(); } catch (e) { return false; }
    if (!list || !list.length) return false;
    var SUFFIX = { "祭": "Fest", "STAR": "STAR", "α": "α" };
    list.forEach(function (c) {
      var base = String(c.file || "").split("/").pop().replace(/\.[a-z0-9]+$/i, "").replace(/^t_/, "");
      if (!base) return;
      var nm = String(c.name || "");
      /* 「アンナ(祭)」のような添え字は残す */
      var m = nm.match(/[（(]([^）)]+)[）)]\s*$/);
      var en = base.replace(/([a-z])([A-Z])/g, "$1 $2");
      if (m) {
        en = en.replace(/(Matsuri|Fes|Fest|Star)$/i, "").trim();
        en += " (" + (SUFFIX[m[1]] || m[1]) + ")";
      }
      if (nm && en && nm !== en) map[nm] = en;
    });
    XevaI18n.add(map);
    return true;
  }
